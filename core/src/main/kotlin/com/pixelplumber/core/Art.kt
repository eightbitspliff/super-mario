    fun tile(t: Int, theme: Theme, groundAbove: Boolean, frame: Int): Sprite? = when (t) {
        T.GROUND -> if (groundAbove) groundFill[theme.ordinal] else groundTop[theme.ordinal]
        T.BRICK -> BRICK
        T.QBLOCK -> QBLOCK[if ((frame / 20) % 4 == 3) 1 else 0]
        T.USED -> USED
        T.HARD -> HARD
        T.PIPE_TL -> PIPE_TL
        T.PIPE_TR -> PIPE_TR
        T.PIPE_L -> PIPE_L
        T.PIPE_R -> PIPE_R
        T.BARRIER -> BARRIER
        T.SEMI -> if (theme == Theme.SKY) SEMI_CLOUD else SEMI
        T.SPIKES -> SPIKES
        T.COIN -> COIN_SPIN[if ((frame / 12) % 4 == 2) 1 else 0]
        T.HILL_L -> HILL_L
        T.HILL_R -> HILL_R
        T.HILL_F -> HILL_F
