    fun create(i: Int): Level = when (i) {
        0 -> l11(); 1 -> l12(); 2 -> l13()
        3 -> l21(); 4 -> l22(); 5 -> l23()
        6 -> l31(); 7 -> l32(); 8 -> l33()
        9 -> l41(); 10 -> l42(); else -> l43()
    }

    private fun lvl(w: Int, s: Int, name: String, theme: Theme, width: Int, mode: Mode = Mode.PLATFORM, f: LevelBuilder.() -> Unit) =
        LevelBuilder(w, s, name, theme, width, mode).apply(f).build()

    /** Treppe zum Tor – wer oben drüber springt, bekommt ein Extraleben. */
    private fun LevelBuilder.finale(x: Int) {
        stairsUp(x, 6)
        hard(x + 6, 8, 2, 6)
        goal(x + 14)
    }

